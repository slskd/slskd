namespace slskd
{
    using System.Collections.Generic;
    using System.Xml.Linq;
    using Microsoft.AspNetCore.DataProtection.Repositories;

    /// <summary>
    ///     An <see cref="IXmlRepository"/> that keeps data protection keys in memory, so that they are never written to disk.
    /// </summary>
    public class DataProtectionKeyRepository : IXmlRepository
    {
        private List<XElement> Elements { get; } = new();
        private object SyncRoot { get; } = new();

        public IReadOnlyCollection<XElement> GetAllElements()
        {
            lock (SyncRoot)
            {
                return Elements.ConvertAll(element => new XElement(element));
            }
        }

        public void StoreElement(XElement element, string friendlyName)
        {
            lock (SyncRoot)
            {
                Elements.Add(new XElement(element));
            }
        }
    }
}
