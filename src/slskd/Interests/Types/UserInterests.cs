namespace slskd.Interests
{
    using System;
    using System.Collections.Generic;

    /// <summary>
    ///     The things a user likes and dislikes.
    /// </summary>
    public record UserInterests
    {
        /// <summary>
        ///     Gets the username of the user.
        /// </summary>
        public string Username { get; init; }

        /// <summary>
        ///     Gets the things the user likes.
        /// </summary>
        public IReadOnlyList<string> Liked { get; init; } = Array.Empty<string>();

        /// <summary>
        ///     Gets the things the user dislikes.
        /// </summary>
        public IReadOnlyList<string> Hated { get; init; } = Array.Empty<string>();
    }
}
